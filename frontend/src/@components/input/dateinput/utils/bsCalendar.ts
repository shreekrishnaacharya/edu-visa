// ─── Core conversion ──────────────────────────────────────────────────────────

/** Days elapsed from reference point to a given AD date */
function adDaysFromRef(adDate: Date): number {
  const utcA = Date.UTC(
    REF_AD.getFullYear(),
    REF_AD.getMonth(),
    REF_AD.getDate(),
  );
  const utcB = Date.UTC(
    adDate.getFullYear(),
    adDate.getMonth(),
    adDate.getDate(),
  );
  return Math.round((utcB - utcA) / 86400000);
}

/** Convert AD date string "YYYY-MM-DD" → BS { year, month, day } */
export function adToBS(adStr: string): {
  year: number;
  month: number;
  day: number;
} {
  const [y, m, d] = adStr.split("-").map(Number);
  let days = adDaysFromRef(new Date(y, m - 1, d));

  let bsY = 2000,
    bsM = 1,
    bsD = 1;
  for (let yr = 2000; yr <= 2099; yr++) {
    const months = BS_DATA[yr];
    if (!months) break;
    for (let mo = 1; mo <= 12; mo++) {
      const dim = months[mo - 1];
      if (days < dim) {
        bsY = yr;
        bsM = mo;
        bsD = days + 1;
        return { year: bsY, month: bsM, day: bsD };
      }
      days -= dim;
    }
  }
  return { year: bsY, month: bsM, day: bsD };
}

/** Convert BS { year, month, day } → AD date string "YYYY-MM-DD" */
export function bsToAD(bsYear: number, bsMonth: number, bsDay: number): string {
  let days = 0;
  for (let yr = 2000; yr < bsYear; yr++) {
    const months = BS_DATA[yr];
    if (!months) break;
    for (let mo = 1; mo <= 12; mo++) days += months[mo - 1];
  }
  const months = BS_DATA[bsYear];
  if (months) {
    for (let mo = 1; mo < bsMonth; mo++) days += months[mo - 1];
  }
  days += bsDay - 1;

  const result = new Date(REF_AD);
  result.setDate(result.getDate() + days);
  const yy = result.getFullYear();
  const mm = String(result.getMonth() + 1).padStart(2, "0");
  const dd = String(result.getDate()).padStart(2, "0");
  return `${yy}-${mm}-${dd}`;
}

/** "YYYY-MM-DD" BS string → AD "YYYY-MM-DD" string */
export function bsStrToAdStr(bsStr: string): string {
  const [y, m, d] = bsStr.split("-").map(Number);
  return bsToAD(y, m, d);
}

/** AD "YYYY-MM-DD" string → BS "YYYY-MM-DD" string */
export function adStrToBsStr(adStr: string): string {
  const { year, month, day } = adToBS(adStr);
  return `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(
    2,
    "0",
  )}`;
}

/** Days in a given BS month */
export function daysInBSMonth(year: number, month: number): number {
  return BS_DATA[year]?.[month - 1] ?? 30;
}

/** First weekday (0=Sun…6=Sat) of a given BS year/month */
export function firstWeekdayOfBSMonth(year: number, month: number): number {
  const adStr = bsToAD(year, month, 1);
  const [y, m, d] = adStr.split("-").map(Number);
  return new Date(y, m - 1, d).getDay();
}

/** Today in BS */
export function todayBS(): { year: number; month: number; day: number } {
  const now = new Date();
  const adStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(
    2,
    "0",
  )}-${String(now.getDate()).padStart(2, "0")}`;
  return adToBS(adStr);
}

/** Navigate BS month: delta = +1 or -1 */
export function navigateBSMonth(
  year: number,
  month: number,
  delta: number,
): { year: number; month: number } {
  let m = month + delta;
  let y = year;
  if (m > 12) {
    m = 1;
    y++;
  }
  if (m < 1) {
    m = 12;
    y--;
  }
  return { year: y, month: m };
}

/** Build the 6×7 calendar grid for a BS month. Empty strings = padding. */
export function buildBSCalendarGrid(
  year: number,
  month: number,
): (number | null)[][] {
  const firstDay = firstWeekdayOfBSMonth(year, month);
  const totalDays = daysInBSMonth(year, month);
  const grid: (number | null)[][] = [];
  let day = 1;
  for (let row = 0; row < 6; row++) {
    const week: (number | null)[] = [];
    for (let col = 0; col < 7; col++) {
      const cell = row * 7 + col;
      if (cell < firstDay || day > totalDays) {
        week.push(null);
      } else {
        week.push(day++);
      }
    }
    grid.push(week);
    if (day > totalDays) break;
  }
  return grid;
}
